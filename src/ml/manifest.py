"""`make manifest`: record every source file with its size and SHA-256, and render data/MANIFEST.md.

data/manifest.json is the record and is committed. A raw archive on disk is hashed again; one that has been deleted
(they are only needed to rebuild Parquet, and the disk here is small) keeps the hash recorded when it was present, so
a fresh download can be checked against it. CRC-32 values come from the downloader's own record, data/raw/ddl/manifest.json.
"""
from __future__ import annotations

import hashlib
import json
import re
from datetime import date
from pathlib import Path

from .settings import ROOT

RAW = ROOT / "data" / "raw" / "ddl"
RECORD = ROOT / "data" / "manifest.json"
URL = "https://www.dropbox.com/sh/hkcde3z2l1h9mq1/AADRe-BuBQ92ozAJiG7YERdCa?dl=1"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        while chunk := fh.read(1 << 20):
            h.update(chunk)
    return h.hexdigest()


def download_date() -> str | None:
    log = ROOT / "logs" / "download.log"
    if log.exists():
        m = re.search(r"^start (\d{4}-\d{2}-\d{2})", log.read_text(encoding="utf8"), re.M)
        if m:
            return m.group(1)
    return None


def update() -> dict:
    record = json.loads(RECORD.read_text()) if RECORD.exists() else {"files": {}}
    record["source"] = "eCourts case records filed 2010-2018 (CSV copies only)"
    record["url"] = URL
    record["downloaded"] = download_date() or record.get("downloaded")
    crc = json.loads((RAW / "manifest.json").read_text()) if (RAW / "manifest.json").exists() else {}
    for name, info in crc.items():
        path = RAW / name
        entry = record["files"].get(name, {})
        entry["bytes"] = info["bytes"]
        entry["crc32"] = f"{info['crc32']:08x}"
        if path.exists():
            if path.stat().st_size != info["bytes"]:
                raise SystemExit(f"{name}: {path.stat().st_size} bytes on disk, {info['bytes']} recorded by the download")
            entry["sha256"] = sha256(path)
            entry["hashed_on"] = date.today().isoformat()
        record["files"][name] = entry
    audit = ROOT / "data" / "parquet" / "load_audit.json"
    if audit.exists():
        record["parquet"] = {k: {"rows": v["parquet_rows"], "bytes": v["parquet_bytes"], "csv_rows": v["csv_rows"]}
                             for k, v in sorted(json.loads(audit.read_text()).items())}
    record["external"] = {p.name: {"bytes": p.stat().st_size, "sha256": sha256(p)}
                          for p in sorted((ROOT / "data" / "external").glob("*.csv"))}
    RECORD.write_text(json.dumps(record, indent=1) + "\n")
    return record


def render(record: dict) -> str:
    raw_rows = "\n".join(
        f"| `{name}` | {info['bytes']:,} | `{info.get('crc32', '')}` | `{info.get('sha256', 'not recorded')}` |"
        for name, info in record["files"].items())
    pq_rows = "\n".join(f"| `{name}` | {info['csv_rows']:,} | {info['rows']:,} | {info['bytes'] / 1e6:,.0f} MB |"
                        for name, info in record.get("parquet", {}).items())
    ext_rows = "\n".join(f"| `data/external/{name}` | {info['bytes']:,} | `{info['sha256']}` |" for name, info in record["external"].items())
    cases = sum(v["rows"] for k, v in record.get("parquet", {}).items() if re.fullmatch(r"cases_\d{4}", k))
    return f"""# Data manifest

Generated by `make manifest` from [data/manifest.json](manifest.json). Every file this project reads, with sizes and hashes,
so a rebuild can prove it used the same inputs.

## Case data

**Source:** Development Data Lab, [judicial data](https://www.devdatalab.org/judicial-data): {record["source"]},
CC BY-NC-SA 4.0 (see [DATA_LICENSE.md](../DATA_LICENSE.md)).
**Downloaded:** {record.get('downloaded') or 'unknown'} by `pipeline/download_ddl.py`, which streams the
5.1 GB Dropbox archive ({record['url']}) and keeps only the CSV members, checking each one's size and CRC-32.

| Archive member (under `data/raw/ddl/`) | Bytes | CRC-32 | SHA-256 |
|---|---|---|---|
{raw_rows}

The archives are only needed to rebuild Parquet, so they may be deleted after `pipeline/load.py` has run; their
hashes stay here. To check a fresh download: `sha256sum data/raw/ddl/csv/cases/cases.tar.gz`, or run `make manifest`,
which stops if a file on disk differs in size from the download's record.

## Parquet built from it

`pipeline/load.py` row counts, CSV rows against Parquet rows ({cases:,} cases in total):

| Table | CSV rows | Parquet rows | Size |
|---|---|---|---|
{pq_rows}

## Other inputs (in git)

| File | Bytes | SHA-256 |
|---|---|---|
{ext_rows}

Their sources are listed in [data/external/SOURCES.md](external/SOURCES.md).
"""


def run() -> None:
    record = update()
    (ROOT / "data" / "MANIFEST.md").write_text(render(record), encoding="utf8")
    print(f"manifest: {len(record['files'])} raw files, {len(record.get('parquet', {}))} Parquet tables, "
          f"{len(record['external'])} external files", flush=True)


if __name__ == "__main__":
    run()
